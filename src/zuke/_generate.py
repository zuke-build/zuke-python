"""The facade generator: the engine's tool spec as the modules of ``zuke.tools``.

``./zuke facades`` reads ``spec/tools.json``, vendored from the engine at the
tag ``spec/engine.json`` names, and writes ``zuke.tools``: ``_tooling.py`` for
the settings base every wrapper's settings extend, and one module per wrapper
package with a class per ``*Tasks`` object and a class per settings class its
tasks reach. A task method takes the body's context, then the task's
parameters, a settings lambda where the task takes a ``configure``, and sends
the engine a ``tool.call`` through :mod:`zuke._facade`. Nothing in
``zuke.tools`` is written by hand; the spec's schema is documented in the
engine repository under ``packages/engine/spec/``.
"""

from __future__ import annotations

import json
import keyword
import re
from collections.abc import Mapping
from dataclasses import dataclass

from zuke._guard import boolean, is_list, record, string

SPEC_VERSION = 1
"""The spec schema this generator reads."""

TOOLING_MODULE = "_tooling"
"""The module the settings base classes are generated into."""

HEADER = """\
# Copyright (c) 2026 the Zuke contributors
# SPDX-License-Identifier: MIT
"""

GENERATED = """\
Generated by ``zuke facades`` from the engine's tool spec; edit the wrapper in
zuke-build/zuke, not this file."""

SCALARS = {
    "string": "str",
    "number": "float",
    "boolean": "bool",
    "null": "None",
    "unknown": "object",
}
"""The Python spelling of each scalar kind."""


def snake_case(name: str) -> str:
    """``camelCase`` to ``snake_case``, as Python names its functions and arguments."""
    spaced = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", spaced).lower()


def python_name(name: str) -> str:
    """The Python name of a member: snake case, suffixed when Python reserves it."""
    snake = snake_case(name)
    reserved = (
        keyword.iskeyword(snake) or keyword.issoftkeyword(snake) or snake == "self"
    )
    return f"{snake}_" if reserved else snake


def docstring(doc: str, indent: str, fallback: str) -> list[str]:
    """A spec doc as a Python docstring, indented; ``fallback`` when it is empty."""
    text = doc.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').strip()
    first, *more = (text or fallback).split("\n")
    if not more:
        return [f'{indent}"""{first}"""']
    return [
        f'{indent}"""{first}',
        *(f"{indent}{line}" if line else "" for line in more),
        f'{indent}"""',
    ]


class Scope:
    """What a module's settings names resolve against: the tooling module's classes."""

    def __init__(self, tooling: frozenset[str]) -> None:
        """A scope over the tooling module's settings classes."""
        self.tooling = tooling
        """The settings classes of the tooling module, importable by name."""
        self.bases: set[str] = set()
        """The tooling classes this module names, imported from the tooling module."""

    def settings(self, name: str) -> str:
        """A settings class by name, an import when the tooling module has it."""
        if name in self.tooling:
            self.bases.add(name)
        return name


def _literal(value: object) -> str:
    """A literal's value as Python spells it."""
    if isinstance(value, bool):
        return "True" if value else "False"
    return json.dumps(value)


def _union(members: list[str]) -> str:
    """Fold rendered members: literals into one ``Literal``, ``None`` last."""
    literals = [m[8:-1] for m in members if m.startswith("Literal[")]
    rest: list[str] = []
    for m in members:
        if not m.startswith("Literal[") and m != "None" and m not in rest:
            rest.append(m)
    parts = [f"Literal[{', '.join(literals)}]", *rest] if literals else rest
    if not parts:
        return "None" if "None" in members else "object"
    joined = "object" if "object" in parts else " | ".join(parts)
    return f"{joined} | None" if "None" in members else joined


def _reference(kind: str, node: dict[str, object], scope: Scope) -> str:
    """The annotation of a type naming something: a class, a lambda, an answer."""
    if kind == "settings":
        return scope.settings(string(node, "name", "type"))
    if kind == "configure":
        settings = scope.settings(string(node, "settings", "type"))
        return f"Callable[[{settings}], {settings}]"
    if kind == "output":
        return "ExecResult"
    if kind == "self":
        return "Self"
    raise ValueError(
        f"type: unknown kind {kind!r}; this generator reads spec {SPEC_VERSION}"
    )


def annotation(t: object, scope: Scope) -> str:
    """The Python annotation of a spec type."""
    node = record(t, "type")
    kind = string(node, "kind", "type")
    if kind in SCALARS:
        return SCALARS[kind]
    if kind == "literal":
        return f"Literal[{_literal(node.get('value'))}]"
    if kind == "union":
        members = node.get("members")
        if not is_list(members):
            raise ValueError("type: a union needs members")
        return _union([annotation(m, scope) for m in members])
    if kind == "array":
        return f"Sequence[{annotation(node.get('element'), scope)}]"
    if kind in {"record", "object"}:
        key, value = (
            ("str", "object")
            if kind == "object"
            else (
                annotation(node.get("key"), scope),
                annotation(node.get("value"), scope),
            )
        )
        return f"Mapping[{key}, {value}]"
    return _reference(kind, node, scope)


@dataclass(frozen=True)
class Param:
    """One parameter of a facade method, as declared and as sent."""

    name: str
    type: str
    optional: bool
    rest: bool
    configures: str | None
    """The settings class a ``configure`` parameter configures, if it is one."""

    def declared(self) -> str:
        """The parameter in the signature."""
        if self.rest:
            return f"*{self.name}: {self.type}"
        return (
            f"{self.name}: {self.type} | None = None"
            if self.optional
            else f"{self.name}: {self.type}"
        )

    def sent(self) -> str:
        """The parameter in the arguments the call sends."""
        if self.configures is not None:
            return f"configured({self.configures}(), {self.name})"
        return f"*{self.name}" if self.rest else self.name


def _params(member: dict[str, object], scope: Scope) -> list[Param]:
    """The parameters of a spec member."""
    declared = member.get("params")
    if not is_list(declared):
        raise ValueError(f"{member.get('name')}: params must be a list")
    out: list[Param] = []
    for p in declared:
        node = record(p, "param")
        type_node = record(node.get("type"), "param type")
        configures = (
            scope.settings(string(type_node, "settings", "type"))
            if type_node.get("kind") == "configure"
            else None
        )
        out.append(
            Param(
                name=python_name(string(node, "name", "param")),
                type=annotation(type_node, scope),
                optional=boolean(node, "optional", "param"),
                rest=boolean(node, "rest", "param"),
                configures=configures,
            )
        )
    return out


def _setter(member: dict[str, object], scope: Scope) -> list[str]:
    """One setter method."""
    name = string(member, "name", "setter")
    params = _params(member, scope)
    returns = record(member.get("returns"), f"{name} returns")
    recorded = ", ".join(
        [json.dumps(name), *(f"*{p.name}" if p.rest else p.name for p in params)]
    )
    kind = returns.get("kind")
    if kind == "self":
        result, body = annotation(returns, scope), f"return self._record({recorded})"
    elif kind == "settings":
        result = annotation(returns, scope)
        body = f"return self._switch({result}, {recorded})"
    else:
        result, body = "None", f"self._record({recorded})"
    signature = ", ".join(["self", *(p.declared() for p in params)])
    return [
        f"    def {python_name(name)}({signature}) -> {result}:",
        *docstring(string(member, "doc", "setter"), "        ", f"`{name}`."),
        f"        {body}",
    ]


def _settings_class(entry: object, scope: Scope) -> list[str]:
    """One settings class, on its spec base or the runtime's ``Settings``."""
    node = record(entry, "settings")
    name = string(node, "name", "settings")
    base = node.get("extends")
    base = scope.settings(base) if isinstance(base, str) else "Settings"
    setters = node.get("setters")
    if not is_list(setters):
        raise ValueError(f"{name}: setters must be a list")
    lines = [
        f"class {name}({base}):",
        *docstring(string(node, "doc", name), "    ", f"Settings of `{name}`."),
    ]
    for setter in setters:
        lines += ["", *_setter(record(setter, "setter"), scope)]
    return lines


def _task(member: dict[str, object], tasks: str, scope: Scope) -> list[str]:
    """One task: a static method sending ``tool.call``."""
    name = string(member, "name", "task")
    params = _params(member, scope)
    answer = annotation(record(member.get("returns"), f"{name} returns"), scope)
    result = answer if answer in {"ExecResult", "None"} else "object"
    sent = ", ".join(p.sent() for p in params)
    where = f"{json.dumps(tasks)}, {json.dumps(name)}"
    call = f"call(ctx, PACKAGE, VERSION, {where}, [{sent}])"
    if result == "ExecResult":
        body = [f"        answer = await {call}", "        return exec_result(answer)"]
    elif result == "None":
        body = [f"        await {call}"]
    else:
        body = [f"        return await {call}"]
    signature = ", ".join(["ctx: ServiceContext", *(p.declared() for p in params)])
    return [
        "    @staticmethod",
        f"    async def {python_name(name)}({signature}) -> {result}:",
        *docstring(string(member, "doc", "task"), "        ", f"`{name}`."),
        *body,
    ]


def _tasks_class(entry: object, scope: Scope) -> list[str]:
    """One ``*Tasks`` class."""
    node = record(entry, "tasks")
    name = string(node, "name", "tasks")
    tasks = node.get("tasks")
    if not is_list(tasks):
        raise ValueError(f"{name}: tasks must be a list")
    lines = [
        f"class {name}:",
        *docstring(string(node, "doc", name), "    ", f"The tasks of `{name}`."),
    ]
    for task in tasks:
        lines += ["", *_task(record(task, "task"), name, scope)]
    return lines


NEEDS = {
    "collections.abc": ("Callable", "Mapping", "Sequence"),
    "typing": ("Literal", "Self"),
    "zuke": ("ExecResult", "ServiceContext"),
    "zuke._facade": ("Settings", "call", "configured", "exec_result"),
}
"""What a module imports from where, by the name a use of it leaves in the body."""

USED = {
    "Settings": r"\(Settings\)",
    "call": r"\bcall\(",
    "configured": r"\bconfigured\(",
    "exec_result": r"\bexec_result\(",
}
"""How a use of a runtime name reads, where the bare name would also match others."""


def _imports(body: str, scope: Scope) -> list[str]:
    """The import lines a module's body needs, read off its code, docstrings aside."""
    code = re.sub(r'"""[\s\S]*?"""', "", body)
    groups: list[list[str]] = [[], []]
    for module, names in NEEDS.items():
        used = [n for n in names if re.search(USED.get(n, rf"\b{n}\b"), code)]
        if used:
            groups[module.startswith("zuke")].append(
                f"from {module} import {', '.join(used)}"
            )
    if scope.bases:
        groups[1].append(
            f"from zuke.tools.{TOOLING_MODULE} import {', '.join(sorted(scope.bases))}"
        )
    return [*groups[0], *([""] if groups[0] and groups[1] else []), *groups[1]]


def _module(doc: str, imports: list[str], body: list[str]) -> str:
    """A module's text: header, docstring, imports, body."""
    parts = [
        HEADER + '"""' + doc + "\n\n" + GENERATED + '\n"""',
        "from __future__ import annotations",
    ]
    if imports:
        parts.append("\n".join(imports))
    if body:
        parts.append("\n".join(body))
    return "\n\n".join(parts) + "\n"


def tooling_module(entries: list[object]) -> str:
    """The tooling module: the settings base classes on the runtime's ``Settings``."""
    scope = Scope(tooling=frozenset())
    body: list[str] = []
    for entry in entries:
        body += ["", *_settings_class(entry, scope)]
    return _module(
        "The settings every wrapper's settings extend: `@zuke/core`'s tooling base.",
        _imports("\n".join(body), scope),
        body,
    )


def package_module(
    entry: object, version: str, tooling: frozenset[str]
) -> tuple[str, str]:
    """A package's module name and text."""
    node = record(entry, "package")
    name = string(node, "name", "package")
    scope = Scope(tooling=tooling)
    body: list[str] = []
    settings, tasks = node.get("settings"), node.get("tasks")
    if not is_list(settings) or not is_list(tasks):
        raise ValueError(f"{name}: settings and tasks must be lists")
    for s in settings:
        body += ["", *_settings_class(s, scope)]
    for t in tasks:
        body += ["", *_tasks_class(t, scope)]
    summary = string(node, "summary", name)
    doc = f"`@zuke/{name}` {version}" + (f": {summary}" if summary else "")
    imports = [
        *_imports("\n".join(body), scope),
        "",
        f"PACKAGE = {json.dumps(name)}",
        f"VERSION = {json.dumps(version)}",
    ]
    return f"{name.replace('-', '_')}.py", _module(doc, imports, body)


def generate(spec: object, versions: Mapping[str, str]) -> dict[str, str]:
    """Every module of ``zuke.tools`` from ``spec``, by file name, in the spec's order.

    ``versions`` names each package's release, which the facade pins in its
    calls; a package the spec has and ``versions`` lacks is an error.
    """
    root = record(spec, "spec")
    if root.get("spec") != SPEC_VERSION:
        raise ValueError(
            f"spec: version {root.get('spec')!r}; this generator reads {SPEC_VERSION}"
        )
    tooling, packages = root.get("tooling"), root.get("packages")
    if not is_list(tooling) or not is_list(packages):
        raise ValueError("spec: tooling and packages must be lists")
    names = frozenset(string(record(t, "tooling"), "name", "tooling") for t in tooling)
    out = {
        "__init__.py": _module(
            "The facades over the engine's wrappers, one module per `@zuke/<package>`.",
            [],
            [],
        ),
        f"{TOOLING_MODULE}.py": tooling_module(tooling),
    }
    for entry in packages:
        name = string(record(entry, "package"), "name", "package")
        if name not in versions:
            raise ValueError(f"spec: no version for @zuke/{name}")
        file, text = package_module(entry, versions[name], names)
        out[file] = text
    return out
