class NodeTasks:
    """Typed task functions for the Node.js runtime `node`."""

    @staticmethod
    async def run(
        ctx: ServiceContext,
        configure: Callable[[NodeRunSettings], NodeRunSettings] | None = None,
    ) -> ExecResult:
        """Run a script: `node [options] <script> [args]`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "NodeTasks",
            "run",
            [configured(NodeRunSettings(), configure)],
        )
        return exec_result(answer)

    @staticmethod
    async def eval(
        ctx: ServiceContext,
        configure: Callable[[NodeEvalSettings], NodeEvalSettings] | None = None,
    ) -> ExecResult:
        """Evaluate inline code: `node --eval <code>`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "NodeTasks",
            "eval",
            [configured(NodeEvalSettings(), configure)],
        )
        return exec_result(answer)

    @staticmethod
    async def test(
        ctx: ServiceContext,
        configure: Callable[[NodeTestSettings], NodeTestSettings] | None = None,
    ) -> ExecResult:
        """Run the built-in test runner: `node --test`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "NodeTasks",
            "test",
            [configured(NodeTestSettings(), configure)],
        )
        return exec_result(answer)

    @staticmethod
    async def evaluate(
        ctx: ServiceContext,
        module: str,
        configure: Callable[[NodeEvaluateSettings], NodeEvaluateSettings] | None = None,
    ) -> object:
        """Import a Node module and resolve to one of its exports' JSON value — the
        way a target reads something *out* of the Node side of a project (an
        OpenAPI document, a resolved config) instead of shelling out to a script
        that has to write it somewhere first.

        `module` is a path, resolved against the working directory. The export
        (`default` unless NodeEvaluateSettings.export names another) is
        awaited; when it is a function it is called with
        NodeEvaluateSettings.callWith's arguments first.

        ```ts
        // tools/openapi.mjs: export default async () => document
        const spec = await NodeTasks.evaluate("tools/openapi.mjs");
        ```

        The evaluation waits for the Node process to exit, so a module that leaves
        a live handle on the event loop (a server, a pool, a timer) would block on
        a value it has already produced. NodeEvaluateSettings.exitAfterResult
        ends the process as soon as the result has been written, for modules in
        that shape.

        The module runs as a real Node process with the build's own permissions —
        the same trust level as a script handed to NodeTasks.run, and the
        reason this is a build-authoring API rather than an input-processing one.
        `module` is code: build it from a literal or from the project's own layout,
        never from an untrusted source (a pull request title, a webhook payload),
        exactly as for every other command a build spawns. Values passed through
        NodeEvaluateSettings.callWith cannot inject into the driver — they
        are embedded as JSON literals — but they do reach the module, so whatever
        the module does with them is the module's contract to uphold.
        """
        return await call(
            ctx,
            PACKAGE,
            VERSION,
            "NodeTasks",
            "evaluate",
            [module, configured(NodeEvaluateSettings(), configure)],
        )
