from __future__ import annotations

from collections.abc import Callable
from typing import Literal, Self

from zuke import ExecResult, ServiceContext
from zuke._facade import call, configured, exec_result
from zuke.tools._tooling import ToolSettings

PACKAGE = "shellcheck"
VERSION = "1.1.0"


class ShellcheckSettings(ToolSettings):
    """Settings for a `shellcheck` run."""

    def paths(self, *values: str) -> Self:
        """Scripts to check (positional); repeatable."""
        return self._record("paths", *values)

    def shell(self, dialect: Literal["sh", "bash", "dash", "ksh", "busybox"]) -> Self:
        """The dialect to analyse as (`-s`/`--shell`), overriding the shebang.

        This is the flag that makes a portability gate mean something: a script
        with a `#!/bin/bash` shebang, or none at all, is otherwise checked as
        bash, so the POSIX violations the gate exists to catch go unreported.
        """
        return self._record("shell", dialect)

    def severity(self, level: Literal["error", "warning", "info", "style"]) -> Self:
        """The lowest severity to report (`-S`/`--severity`)."""
        return self._record("severity", level)

    def format(
        self,
        value: Literal["tty", "gcc", "checkstyle", "diff", "json", "json1", "quiet"],
    ) -> Self:
        """The output format (`-f`/`--format`)."""
        return self._record("format", value)

    def exclude(self, *codes: str) -> Self:
        """Suppress specific checks by code (`-e`/`--exclude`); repeatable. Codes may
        be given with or without the `SC` prefix, as ShellCheck accepts both.
        """
        return self._record("exclude", *codes)

    def external_sources(self) -> Self:
        """Follow `source`d files outside the checked set (`-x`/`--external-sources`)."""
        return self._record("externalSources")


class ShellcheckTasks:
    """Typed task functions for the ShellCheck static analyser."""

    @staticmethod
    async def lint(
        ctx: ServiceContext,
        configure: Callable[[ShellcheckSettings], ShellcheckSettings] | None = None,
    ) -> ExecResult:
        """Analyse shell scripts with `shellcheck`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "ShellcheckTasks",
            "lint",
            [configured(ShellcheckSettings(), configure)],
        )
        return exec_result(answer)
