from __future__ import annotations

from collections.abc import Callable
from typing import Literal, Self

from zuke import ExecResult, ServiceContext
from zuke._facade import call, configured, exec_result
from zuke.tools._tooling import ToolSettings

PACKAGE = "dpdm"
VERSION = "1.1.0"


class DpdmAnalyzeSettings(ToolSettings):
    """Settings for a `dpdm` analysis run."""

    def transform(self) -> Self:
        """Transform TypeScript modules to JavaScript before analysis (`--transform`)."""
        return self._record("transform")

    def no_tree(self) -> Self:
        """Suppress the dependency tree output (`--no-tree`)."""
        return self._record("noTree")

    def no_circular(self) -> Self:
        """Suppress the circular-dependency output (`--no-circular`)."""
        return self._record("noCircular")

    def no_warning(self) -> Self:
        """Suppress warnings about unresolved/missing modules (`--no-warning`)."""
        return self._record("noWarning")

    def no_progress(self) -> Self:
        """Disable the progress bar (`--no-progress`)."""
        return self._record("noProgress")

    def output(self, path: str) -> Self:
        """Write the analysis as JSON to a file (`--output`)."""
        return self._record("output", path)

    def tsconfig(self, path: str) -> Self:
        """Use an explicit tsconfig for module resolution (`--tsconfig`)."""
        return self._record("tsconfig", path)

    def context(self, path: str) -> Self:
        """Set the context directory used to shorten printed paths (`--context`)."""
        return self._record("context", path)

    def extensions(self, *exts: str) -> Self:
        """Extensions to resolve, e.g. `.ts`, `.tsx` (`--extensions`)."""
        return self._record("extensions", *exts)

    def js(self, *exts: str) -> Self:
        """Extensions treated as JavaScript-like (`--js`)."""
        return self._record("js", *exts)

    def include(self, pattern: str) -> Self:
        """Only analyze files matching this regular expression (`--include`)."""
        return self._record("include", pattern)

    def exclude(self, pattern: str) -> Self:
        """Skip files matching this regular expression (`--exclude`)."""
        return self._record("exclude", pattern)

    def skip_dynamic_imports(self, mode: Literal["circular", "tree"]) -> Self:
        """Skip dynamic imports when detecting `circular` or `tree` (`--skip-dynamic-imports`)."""
        return self._record("skipDynamicImports", mode)

    def detect_unused_files_from(self, glob: str) -> Self:
        """Detect unused files starting from this glob (`--detect-unused-files-from`)."""
        return self._record("detectUnusedFilesFrom", glob)

    def exit_code(self, rule: str) -> Self:
        """Exit with a code when a case occurs, e.g. `circular:1` (`--exit-code`)."""
        return self._record("exitCode", rule)

    def entries(self, *paths: str) -> Self:
        """The entry files or globs to analyze (appended after all options)."""
        return self._record("entries", *paths)


class DpdmTasks:
    """Typed task functions for the `dpdm` CLI."""

    @staticmethod
    async def analyze(
        ctx: ServiceContext,
        configure: Callable[[DpdmAnalyzeSettings], DpdmAnalyzeSettings] | None = None,
    ) -> ExecResult:
        """Analyze dependencies and circular imports: `dpdm <flags> <entries...>`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "DpdmTasks",
            "analyze",
            [configured(DpdmAnalyzeSettings(), configure)],
        )
        return exec_result(answer)
