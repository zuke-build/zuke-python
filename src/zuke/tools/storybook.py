"""`@zuke/storybook` 1.0.0: `@zuke/storybook` — typed [Storybook](https://storybook.js.org) CLI task wrappers for Zuke builds.

Generated by ``zuke facades`` from the engine's tool spec; edit the wrapper in
zuke-build/zuke, not this file.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Self

from zuke import ExecResult, ServiceContext
from zuke._facade import call, configured, exec_result
from zuke.tools._tooling import ToolSettings

PACKAGE = "storybook"
VERSION = "1.0.0"


class StorybookSettings(ToolSettings):
    """Base for all `storybook` subcommand settings: the binary is `storybook`,
    with the `--config-dir` option every subcommand accepts.
    """

    def config_dir(self, path: str) -> Self:
        """Read the configuration from this directory instead of `.storybook` (`--config-dir`)."""
        return self._record("configDir", path)


class StorybookDevSettings(StorybookSettings):
    """Settings for `storybook dev` (the development server)."""

    def port(self, value: float) -> Self:
        """Serve on a specific port (`--port`)."""
        return self._record("port", value)

    def host(self, value: str) -> Self:
        """Bind to a host/IP (`--host`)."""
        return self._record("host", value)

    def no_open(self) -> Self:
        """Do not open the browser on start (`--no-open`)."""
        return self._record("noOpen")

    def ci(self) -> Self:
        """Never prompt and never open a browser (`--ci`).

        A build step is not a terminal someone is watching: without this Storybook
        can stop on an interactive question and hang the run.
        """
        return self._record("ci")


class StorybookBuildSettings(StorybookSettings):
    """Settings for `storybook build` (the static build)."""

    def output_dir(self, path: str) -> Self:
        """Write the static build to this directory (`--output-dir`)."""
        return self._record("outputDir", path)

    def quiet_output(self) -> Self:
        """Suppress the progress output, leaving warnings and errors (`--quiet`).

        Named `quietOutput` because `ToolSettings.quiet()` already means "do not
        stream the process output to the terminal", which is a different thing.
        """
        return self._record("quietOutput")


class StorybookTasks:
    """Typed task functions for the `storybook` CLI."""

    @staticmethod
    async def dev(
        ctx: ServiceContext,
        configure: Callable[[StorybookDevSettings], StorybookDevSettings] | None = None,
    ) -> ExecResult:
        """Start the development server: `storybook dev`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "StorybookTasks",
            "dev",
            [configured(StorybookDevSettings(), configure)],
        )
        return exec_result(answer)

    @staticmethod
    async def build(
        ctx: ServiceContext,
        configure: Callable[[StorybookBuildSettings], StorybookBuildSettings]
        | None = None,
    ) -> ExecResult:
        """Build the static Storybook: `storybook build`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "StorybookTasks",
            "build",
            [configured(StorybookBuildSettings(), configure)],
        )
        return exec_result(answer)
