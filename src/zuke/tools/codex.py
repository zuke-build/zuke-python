from __future__ import annotations

from collections.abc import Callable
from typing import Literal, Self

from zuke import ExecResult, ServiceContext
from zuke._facade import call, configured, exec_result
from zuke.tools._tooling import SubcommandSettings, ToolSettings

PACKAGE = "codex"
VERSION = "1.1.2"


class CodexExecSettings(ToolSettings):
    """Settings for a non-interactive `codex exec` run — the build-friendly way to
    send a single prompt and capture the response.
    """

    def prompt(self, text: str) -> Self:
        """The prompt to run non-interactively. Omit to read from stdin."""
        return self._record("prompt", text)

    def model(self, id: str) -> Self:
        """Pin the model, e.g. `model("gpt-5-codex")` (`--model`)."""
        return self._record("model", id)

    def image(self, *paths: str) -> Self:
        """Attach an image to the prompt (`--image`). Repeatable."""
        return self._record("image", *paths)

    def config(self, key: str, value: str) -> Self:
        """Override a config value as `key=value` (`--config`). Repeatable."""
        return self._record("config", key, value)

    def sandbox(
        self, mode: Literal["read-only", "workspace-write", "danger-full-access"]
    ) -> Self:
        """Sandbox policy for model-generated commands (`--sandbox`)."""
        return self._record("sandbox", mode)

    def cd(self, dir: str) -> Self:
        """Run as if `codex` was started in this directory (`--cd`)."""
        return self._record("cd", dir)

    def ask_for_approval(
        self, policy: Literal["untrusted", "on-failure", "on-request", "never"]
    ) -> Self:
        """Approval policy for the run (`--ask-for-approval`)."""
        return self._record("askForApproval", policy)

    def full_auto(self) -> Self:
        """Low-friction sandboxed automatic execution (`--full-auto`)."""
        return self._record("fullAuto")

    def dangerously_bypass_approvals_and_sandbox(self) -> Self:
        """Skip all confirmation prompts and sandboxing (`--dangerously-bypass-approvals-and-sandbox`)."""
        return self._record("dangerouslyBypassApprovalsAndSandbox")

    def skip_git_repo_check(self) -> Self:
        """Allow running outside a Git repository (`--skip-git-repo-check`)."""
        return self._record("skipGitRepoCheck")

    def json(self) -> Self:
        """Emit events as newline-delimited JSON (`--json`)."""
        return self._record("json")

    def output_last_message(self, file: str) -> Self:
        """Write the agent's final message to a file (`--output-last-message`)."""
        return self._record("outputLastMessage", file)

    def output_schema(self, file: str) -> Self:
        """Constrain the final message to a JSON schema file (`--output-schema`)."""
        return self._record("outputSchema", file)

    def color(self, mode: Literal["always", "never", "auto"]) -> Self:
        """When to colourise output (`--color`)."""
        return self._record("color", mode)

    def profile(self, name: str) -> Self:
        """Use a named configuration profile (`--profile`)."""
        return self._record("profile", name)

    def oss(self) -> Self:
        """Use a local open-source model provider (`--oss`)."""
        return self._record("oss")


class CodexMcpSettings(SubcommandSettings):
    """Settings for a `codex mcp …` invocation (manage MCP servers): name the verb
    and operands with `.command(...)` and pass anything else with `.flag(...)`.
    """


class CodexTasks:
    """Typed task functions for the OpenAI Codex CLI."""

    @staticmethod
    async def exec(
        ctx: ServiceContext,
        configure: Callable[[CodexExecSettings], CodexExecSettings] | None = None,
    ) -> ExecResult:
        """Run a prompt non-interactively (`codex exec`)."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "CodexTasks",
            "exec",
            [configured(CodexExecSettings(), configure)],
        )
        return exec_result(answer)

    @staticmethod
    async def mcp(
        ctx: ServiceContext,
        configure: Callable[[CodexMcpSettings], CodexMcpSettings] | None = None,
    ) -> ExecResult:
        """Manage MCP servers (`codex mcp …`)."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "CodexTasks",
            "mcp",
            [configured(CodexMcpSettings(), configure)],
        )
        return exec_result(answer)
