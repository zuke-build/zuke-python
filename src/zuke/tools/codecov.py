from __future__ import annotations

from collections.abc import Callable
from typing import Self

from zuke import ExecResult, ServiceContext
from zuke._facade import call, configured, exec_result
from zuke.tools._tooling import ToolSettings

PACKAGE = "codecov"
VERSION = "1.1.0"


class CodecovUploadSettings(ToolSettings):
    """Settings for `codecovcli upload-process`."""

    def files(self, *paths: str) -> Self:
        """A coverage report file to upload (`--file`). Repeatable."""
        return self._record("files", *paths)

    def flags(self, *names: str) -> Self:
        """Tag the uploaded reports with a flag (`--flag`). Repeatable."""
        return self._record("flags", *names)

    def plugins(self, *names: str) -> Self:
        """Run an upload plugin, e.g. `gcov` or `noop` (`--plugin`). Repeatable."""
        return self._record("plugins", *names)

    def token(self, value: str) -> Self:
        """Repository upload token.

        Routed through `CODECOV_TOKEN` rather than `--token`, because a child's
        argv is world-readable: `ps` or `/proc/<pid>/cmdline` shows it to every
        other user on the host and to every process the build starts. The
        environment of another process is not readable the same way, and the CLI
        documents the variable, so nothing is given up by preferring it.

        Also registered with the run's redactor, so a value that reaches the
        output some other way — an error message quoting a URL, a tool echoing its
        own configuration — is masked there too.
        """
        return self._record("token", value)

    def slug(self, value: str) -> Self:
        """Repository slug as `OWNER/REPO` (`--slug`)."""
        return self._record("slug", value)

    def sha(self, value: str) -> Self:
        """Commit SHA the coverage belongs to (`--sha`)."""
        return self._record("sha", value)

    def branch(self, value: str) -> Self:
        """Branch the coverage belongs to (`--branch`)."""
        return self._record("branch", value)

    def pull_request(self, value: str | float) -> Self:
        """Pull request number the coverage belongs to (`--pr`)."""
        return self._record("pullRequest", value)

    def git_service(self, value: str) -> Self:
        """Git host the repo lives on, e.g. `github` (`--git-service`)."""
        return self._record("gitService", value)

    def name(self, value: str) -> Self:
        """A custom display name for this upload (`--name`)."""
        return self._record("name", value)

    def dir(self, value: str) -> Self:
        """Directory to search for coverage reports (`--dir`)."""
        return self._record("dir", value)

    def network_root_folder(self, value: str) -> Self:
        """Root folder used to resolve report file paths (`--network-root-folder`)."""
        return self._record("networkRootFolder", value)

    def report_type(self, value: str) -> Self:
        """Report kind: `coverage` (default) or `test_results` (`--report-type`)."""
        return self._record("reportType", value)

    def disable_telem(self) -> Self:
        """Keep the CLI from reporting its own errors to Codecov's Sentry
        (`--disable-telem`). A global flag, so it is emitted before the subcommand.
        """
        return self._record("disableTelem")

    def disable_search(self) -> Self:
        """Upload only the named files, skipping the auto-search (`--disable-search`)."""
        return self._record("disableSearch")

    def handle_no_reports_found(self) -> Self:
        """Succeed instead of erroring when no reports are found (`--handle-no-reports-found`)."""
        return self._record("handleNoReportsFound")

    def fail_on_error(self) -> Self:
        """Exit non-zero when the upload fails (`--fail-on-error`)."""
        return self._record("failOnError")

    def dry_run(self) -> Self:
        """Print what would be uploaded without sending anything (`--dry-run`)."""
        return self._record("dryRun")


class CodecovTasks:
    """Typed task functions for the Codecov CLI."""

    @staticmethod
    async def upload(
        ctx: ServiceContext,
        configure: Callable[[CodecovUploadSettings], CodecovUploadSettings]
        | None = None,
    ) -> ExecResult:
        """Upload coverage reports: `codecovcli upload-process`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "CodecovTasks",
            "upload",
            [configured(CodecovUploadSettings(), configure)],
        )
        return exec_result(answer)
