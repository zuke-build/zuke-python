from __future__ import annotations

from collections.abc import Callable
from typing import Self

from zuke import ExecResult, ServiceContext
from zuke._facade import call, configured, exec_result
from zuke.tools._tooling import ToolSettings

PACKAGE = "knip"
VERSION = "1.1.0"


class KnipRunSettings(ToolSettings):
    """Settings for a `knip` run."""

    def production(self) -> Self:
        """Restrict analysis to production code paths (`--production`)."""
        return self._record("production")

    def strict(self) -> Self:
        """Treat the production set strictly (`--strict`)."""
        return self._record("strict")

    def fix(self) -> Self:
        """Auto-remove unused exports/dependencies where possible (`--fix`)."""
        return self._record("fix")

    def cache(self) -> Self:
        """Enable the analysis cache (`--cache`)."""
        return self._record("cache")

    def no_exit_code(self) -> Self:
        """Always exit 0, even when issues are found (`--no-exit-code`)."""
        return self._record("noExitCode")

    def config(self, path: str) -> Self:
        """Use an explicit config file (`--config`)."""
        return self._record("config", path)

    def workspace(self, name: str) -> Self:
        """Restrict to a single workspace (`--workspace`)."""
        return self._record("workspace", name)

    def reporter(self, name: str) -> Self:
        """Choose the reporter, e.g. `json` or `compact` (`--reporter`)."""
        return self._record("reporter", name)

    def include(self, *types: str) -> Self:
        """Limit to specific issue types, e.g. `files`, `dependencies` (`--include`)."""
        return self._record("include", *types)


class KnipTasks:
    """Typed task functions for the `knip` CLI."""

    @staticmethod
    async def run(
        ctx: ServiceContext,
        configure: Callable[[KnipRunSettings], KnipRunSettings] | None = None,
    ) -> ExecResult:
        """Find unused files, dependencies, and exports: `knip`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "KnipTasks",
            "run",
            [configured(KnipRunSettings(), configure)],
        )
        return exec_result(answer)
