from __future__ import annotations

from collections.abc import Callable
from typing import Literal, Self

from zuke import ExecResult, ServiceContext
from zuke._facade import call, configured, exec_result
from zuke.tools._tooling import ToolSettings

PACKAGE = "tsup"
VERSION = "1.0.1"


class TsupBuildSettings(ToolSettings):
    """Settings for a `tsup` bundle run."""

    def entry(self, *paths: str) -> Self:
        """Entry point(s) to bundle (positional); repeatable."""
        return self._record("entry", *paths)

    def format(self, *formats: Literal["esm", "cjs", "iife"]) -> Self:
        """Output format(s), joined into `--format` (e.g. `esm,cjs`)."""
        return self._record("format", *formats)

    def dts(self) -> Self:
        """Emit TypeScript declaration files (`--dts`)."""
        return self._record("dts")

    def minify(self) -> Self:
        """Minify the output (`--minify`)."""
        return self._record("minify")

    def sourcemap(self) -> Self:
        """Emit source maps (`--sourcemap`)."""
        return self._record("sourcemap")

    def clean(self) -> Self:
        """Clean the output directory before building (`--clean`)."""
        return self._record("clean")

    def watch(self) -> Self:
        """Rebuild on change (`--watch`)."""
        return self._record("watch")

    def out_dir(self, path: str) -> Self:
        """Output directory (`--out-dir`)."""
        return self._record("outDir", path)

    def target(self, value: str) -> Self:
        """Compilation target, e.g. `es2022` or `node18` (`--target`)."""
        return self._record("target", value)

    def tsconfig(self, path: str) -> Self:
        """Path to a tsconfig file (`--tsconfig`)."""
        return self._record("tsconfig", path)

    def config(self, path: str) -> Self:
        """Path to a tsup config file (`--config`)."""
        return self._record("config", path)


class TsupTasks:
    """Typed task functions for the `tsup` bundler."""

    @staticmethod
    async def build(
        ctx: ServiceContext,
        configure: Callable[[TsupBuildSettings], TsupBuildSettings] | None = None,
    ) -> ExecResult:
        """Bundle the entry points: `tsup`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "TsupTasks",
            "build",
            [configured(TsupBuildSettings(), configure)],
        )
        return exec_result(answer)
