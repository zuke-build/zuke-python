"""`@zuke/jsr` 1.0.2: `@zuke/jsr` — tools for the [JSR](https://jsr.io) registry in Zuke builds: typed `JsrTasks` wrappers for the `jsr` CLI (publish, add, remove), plus read-only registry queries to check which versions are already published.

Generated by ``zuke facades`` from the engine's tool spec; edit the wrapper in
zuke-build/zuke, not this file.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Self

from zuke import ExecResult, ServiceContext
from zuke._facade import call, configured, exec_result
from zuke.tools._tooling import ToolSettings

PACKAGE = "jsr"
VERSION = "1.0.2"


class JsrSettings(ToolSettings):
    """Base for all `jsr` subcommand settings: the binary is `jsr`."""


class JsrAddSettings(JsrSettings):
    """Settings for `jsr add` (install a JSR dependency)."""

    def packages(self, *specs: str) -> Self:
        """Package specs to add, e.g. `@std/assert` (required)."""
        return self._record("packages", *specs)

    def dev(self) -> Self:
        """Add as a development dependency (`--save-dev`)."""
        return self._record("dev")


class JsrPublishSettings(JsrSettings):
    """Settings for `jsr publish`."""

    def dry_run(self) -> Self:
        """Validate without publishing (`--dry-run`)."""
        return self._record("dryRun")

    def allow_slow_types(self) -> Self:
        """Permit slow types in the published package (`--allow-slow-types`)."""
        return self._record("allowSlowTypes")

    def allow_dirty(self) -> Self:
        """Publish even with an uncommitted working tree (`--allow-dirty`)."""
        return self._record("allowDirty")

    def no_check(self) -> Self:
        """Skip type-checking before publishing (`--no-check`)."""
        return self._record("noCheck")

    def provenance(self) -> Self:
        """Attach provenance attestation in CI (`--provenance`)."""
        return self._record("provenance")

    def token(self, value: str) -> Self:
        """Authenticate with a token instead of the interactive flow (`--token`).

        Registered with the run's redactor, so every *rendering* of the command
        masks it — a dry-run echo, a failure message. That is as far as it goes:
        `jsr publish` accepts the token only as a flag, so the value still reaches
        the child's argv, where `ps` and `/proc/<pid>/cmdline` expose it to every
        other user on the host and to every process the build starts. There is no
        environment variable to move it to.

        On GitHub Actions, prefer OIDC and pass no token at all: the publish is
        authenticated by the workflow's identity, so there is no credential to
        expose. This is for the cases where that is not available.
        """
        return self._record("token", value)


class JsrRemoveSettings(JsrSettings):
    """Settings for `jsr remove`."""

    def packages(self, *names: str) -> Self:
        """Package names to remove (required)."""
        return self._record("packages", *names)


class JsrTasks:
    """Typed task functions for the `jsr` CLI."""

    @staticmethod
    async def publish(
        ctx: ServiceContext,
        configure: Callable[[JsrPublishSettings], JsrPublishSettings] | None = None,
    ) -> ExecResult:
        """Publish the package: `jsr publish`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "JsrTasks",
            "publish",
            [configured(JsrPublishSettings(), configure)],
        )
        return exec_result(answer)

    @staticmethod
    async def add(
        ctx: ServiceContext,
        configure: Callable[[JsrAddSettings], JsrAddSettings] | None = None,
    ) -> ExecResult:
        """Add a JSR dependency: `jsr add`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "JsrTasks",
            "add",
            [configured(JsrAddSettings(), configure)],
        )
        return exec_result(answer)

    @staticmethod
    async def remove(
        ctx: ServiceContext,
        configure: Callable[[JsrRemoveSettings], JsrRemoveSettings] | None = None,
    ) -> ExecResult:
        """Remove a dependency: `jsr remove`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "JsrTasks",
            "remove",
            [configured(JsrRemoveSettings(), configure)],
        )
        return exec_result(answer)
