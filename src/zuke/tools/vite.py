class ViteDevSettings(ViteSettings):
    """Settings for `vite dev` (the development server)."""

    def host(self, value: str) -> Self:
        """Bind to a host/IP (`--host`)."""
        return self._record("host", value)

    def port(self, value: float) -> Self:
        """Serve on a specific port (`--port`)."""
        return self._record("port", value)

    def strict_port(self) -> Self:
        """Fail instead of trying the next free port when port is taken
        (`--strictPort`).

        A build that hands the port to something else — an e2e runner, a health
        check — needs the server to be on the port it asked for or not at all;
        without this Vite silently moves on and the other side connects to nothing.
        """
        return self._record("strictPort")

    def open(self) -> Self:
        """Open the app in the browser on start (`--open`)."""
        return self._record("open")


