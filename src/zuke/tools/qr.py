from __future__ import annotations

from collections.abc import Callable
from typing import Literal, Self

from zuke import ServiceContext
from zuke._facade import Settings, call, configured

PACKAGE = "qr"
VERSION = "1.2.0"


class QrSettings(Settings):
    """Configuration for encoding and rendering a QR code, set through a lambda
    passed to a `QrTasks` method. Every setter returns `this` so calls chain.
    """

    def error_correction(self, level: Literal["L", "M", "Q", "H"]) -> Self:
        """Set the error-correction level: `"L"` (~7%), `"M"` (~15%), `"Q"` (~25%) or `"H"` (~30%)."""
        return self._record("errorCorrection", level)

    def boost_error_correction(self, enabled: bool | None = None) -> Self:
        """Whether to raise the error-correction level when a higher one fits the
        same version. On by default; turn it off to get exactly the level asked for.
        """
        return self._record("boostErrorCorrection", enabled)

    def quiet_zone(self, modules: float) -> Self:
        """Set the width of the light border around the symbol, in modules (0 to MAX_QUIET_ZONE)."""
        return self._record("quietZone", modules)

    def invert(self, enabled: bool | None = None) -> Self:
        """Swap the colours: light modules become blocks and dark ones spaces. Use it
        on a terminal whose text is light on dark, where the default rendering
        shows the code with dark and light exchanged.
        """
        return self._record("invert", enabled)

    def compact(self, enabled: bool | None = None) -> Self:
        """Whether to draw two module rows per line with `▀`/`▄`/`█` (the default,
        which keeps a version-3 code under 20 lines) or one row per line with a
        two-character `██` cell per module.
        """
        return self._record("compact", enabled)


class QrTasks:
    """Task-shaped QR code operations. Each method takes the text to encode (a URL,
    usually) and an optional settings lambda:

    ```ts
    import { QrTasks } from "@zuke/qr";

    QrTasks.print("https://zuke.build", (s) => s.errorCorrection("Q"));
    ```
    """

    @staticmethod
    async def encode(
        ctx: ServiceContext,
        text: str,
        configure: Callable[[QrSettings], QrSettings] | None = None,
    ) -> object:
        """Encode `text` (as UTF-8, byte mode) into a QrCode matrix."""
        return await call(
            ctx,
            PACKAGE,
            VERSION,
            "QrTasks",
            "encode",
            [text, configured(QrSettings(), configure)],
        )

    @staticmethod
    async def render_lines(
        ctx: ServiceContext,
        text: str,
        configure: Callable[[QrSettings], QrSettings] | None = None,
    ) -> object:
        """Encode `text` and render it as terminal lines (see QrSettings.compact)."""
        return await call(
            ctx,
            PACKAGE,
            VERSION,
            "QrTasks",
            "renderLines",
            [text, configured(QrSettings(), configure)],
        )

    @staticmethod
    async def render(
        ctx: ServiceContext,
        text: str,
        configure: Callable[[QrSettings], QrSettings] | None = None,
    ) -> object:
        """Encode `text` and render it as one newline-joined string."""
        return await call(
            ctx,
            PACKAGE,
            VERSION,
            "QrTasks",
            "render",
            [text, configured(QrSettings(), configure)],
        )
