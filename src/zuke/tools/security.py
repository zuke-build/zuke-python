class GitleaksDetectSettings(ToolSettings):
    """Settings for [`gitleaks detect`](https://github.com/gitleaks/gitleaks), which
    scans a directory (and, by default, git history) for committed secrets.
    """

    def source(self, path: str) -> Self:
        """Path to scan (`--source`)."""
        return self._record("source", path)

    def config(self, path: str) -> Self:
        """Use an explicit gitleaks config (`--config`)."""
        return self._record("config", path)

    def report_format(self, value: str) -> Self:
        """Report format (`--report-format`), e.g. `json`, `sarif`, `csv`."""
        return self._record("reportFormat", value)

    def report_path(self, path: str) -> Self:
        """Write the report to a file (`--report-path`)."""
        return self._record("reportPath", path)

    def redact(self) -> Self:
        """Redact secret values from the output (`--redact`)."""
        return self._record("redact")

    def no_git(self) -> Self:
        """Treat the source as a plain directory, not a git repo (`--no-git`)."""
        return self._record("noGit")

    def verbose(self) -> Self:
        """Verbose output (`--verbose`)."""
        return self._record("verbose")

    def log_opts(self, opts: str) -> Self:
        """Restrict which commits are scanned, passed straight through to `git log`
        (`--log-opts`).

        Without this, `gitleaks detect` walks the whole history reachable from the
        refs present in the checkout — so on a pull request, where CI typically
        fetches every branch, a secret-shaped string on an unrelated branch fails
        the scan and the failure appears on whichever pull request is looked at.
        Passing a range such as `origin/main..HEAD` scopes the scan to the commits
        under review.

        Has no effect alongside noGit, which makes gitleaks treat the
        source as a plain directory and ignore history entirely.
        """
        return self._record("logOpts", opts)


