from typing import Self

from zuke import ExecResult, ServiceContext
from zuke._facade import call, configured, exec_result
from zuke.tools._tooling import ToolSettings

PACKAGE = "cspell"
VERSION = "1.2.0"


class CspellSettings(ToolSettings):
    """Settings for a `cspell lint` run."""

    def files(self, *globs: str) -> Self:
        """Files or globs to check (positional); repeatable."""
        return self._record("files", *globs)

    def config(self, path: str) -> Self:
        """Use an explicit config file (`-c`/`--config`)."""
        return self._record("config", path)

    def no_progress(self) -> Self:
        """Suppress the progress output (`--no-progress`)."""
        return self._record("noProgress")

    def no_summary(self) -> Self:
        """Suppress the summary line (`--no-summary`)."""
        return self._record("noSummary")

    def show_suggestions(self) -> Self:
        """Print spelling suggestions for each issue (`--show-suggestions`)."""
        return self._record("showSuggestions")

    def show_context(self) -> Self:
        """Print the surrounding line for each issue (`--show-context`)."""
        return self._record("showContext")

    def quiet_output(self) -> Self:
        """Only emit issues, hiding informational output (`--quiet`)."""
        return self._record("quietOutput")

    def cache(self) -> Self:
        """Cache results between runs (`--cache`)."""
        return self._record("cache")

    def dot(self) -> Self:
        """Include dotfiles and dot-directories (`--dot`)."""
        return self._record("dot")

    def gitignore(self) -> Self:
        """Honour `.gitignore` files (`--gitignore`)."""
        return self._record("gitignore")

    def gitignore_root(self, path: str) -> Self:
        """Stop the `.gitignore` search at this directory (`--gitignore-root`).

        Without it cspell keeps walking up past the repository root and can pick up
        an unrelated `.gitignore` from a parent directory — so a run inside a git
        worktree, whose checkout lives outside the main working tree, sees ignore
        rules that do not belong to it. Point this at the repository root to bound
        the search.
        """
        return self._record("gitignoreRoot", path)

    def no_must_find_files(self) -> Self:
        """Exit successfully when a glob matches nothing (`--no-must-find-files`).

        cspell fails by default if any file argument matched no files. A run scoped
        to a computed file list — the staged files, the files a diff touched — can
        legitimately be empty, so a file-scoped run wants this.
        """
        return self._record("noMustFindFiles")

    def unique(self) -> Self:
        """Report each unique issue only once (`--unique`)."""
        return self._record("unique")

    def locale(self, value: str) -> Self:
        """Restrict to a locale, e.g. `en,en-GB` (`--locale`)."""
        return self._record("locale", value)

    def exclude(self, glob: str) -> Self:
        """Exclude files matching a glob (`-e`/`--exclude`); repeatable."""
        return self._record("exclude", glob)

    def max_duplicate_problems(self, count: float) -> Self:
        """Cap the number of duplicate problems reported (`--max-duplicate-problems`)."""
        return self._record("maxDuplicateProblems", count)


class CspellTasks:
    """Typed task functions for the `cspell` spell-checker."""

    @staticmethod
    async def lint(
        ctx: ServiceContext,
        configure: Callable[[CspellSettings], CspellSettings] | None = None,
    ) -> ExecResult:
        """Spell-check with `cspell lint`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "CspellTasks",
            "lint",
            [configured(CspellSettings(), configure)],
        )
        return exec_result(answer)
