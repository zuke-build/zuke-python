from __future__ import annotations

from collections.abc import Callable

from zuke import ExecResult, ServiceContext
from zuke._facade import call, configured, exec_result
from zuke.tools._tooling import ToolSettings

PACKAGE = "cmd"
VERSION = "1.0.1"


class CmdSettings(ToolSettings):
    """Settings for a generic command: the tool name plus raw arguments."""


class CmdTasks:
    """Task functions for running arbitrary tools."""

    @staticmethod
    async def exec(
        ctx: ServiceContext,
        tool: str,
        configure: Callable[[CmdSettings], CmdSettings] | None = None,
    ) -> ExecResult:
        """Run `tool` with the configured settings."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "CmdTasks",
            "exec",
            [tool, configured(CmdSettings(), configure)],
        )
        return exec_result(answer)
