from __future__ import annotations

from collections.abc import Callable
from typing import Self

from zuke import ExecResult, ServiceContext
from zuke._facade import call, configured, exec_result
from zuke.tools._tooling import ToolSettings

PACKAGE = "turbo"
VERSION = "1.0.1"


class TurboSettings(ToolSettings):
    """Base for all `turbo` subcommand settings: the binary is `turbo`."""


class TurboPruneSettings(TurboSettings):
    """Settings for `turbo prune`."""

    def package(self, name: str) -> Self:
        """The package to prune the workspace down to (required)."""
        return self._record("package", name)

    def docker(self) -> Self:
        """Produce a Docker-friendly layout (`--docker`)."""
        return self._record("docker")

    def out_dir(self, path: str) -> Self:
        """Output directory (`--out-dir`)."""
        return self._record("outDir", path)


class TurboRunSettings(TurboSettings):
    """Settings for `turbo run`."""

    def tasks(self, *names: str) -> Self:
        """The package.json task(s) to run (positional; at least one required)."""
        return self._record("tasks", *names)

    def filter(self, pattern: str) -> Self:
        """Restrict to matching packages (`--filter`); repeatable."""
        return self._record("filter", pattern)

    def parallel(self) -> Self:
        """Run tasks in parallel, ignoring dependencies (`--parallel`)."""
        return self._record("parallel")

    def concurrency(self, value: str) -> Self:
        """Limit concurrency, e.g. `10` or `50%` (`--concurrency`)."""
        return self._record("concurrency", value)

    def force(self) -> Self:
        """Ignore cache hits and force execution (`--force`)."""
        return self._record("force")

    def no_cache(self) -> Self:
        """Disable reading and writing the cache (`--no-cache`)."""
        return self._record("noCache")

    def continue_(self) -> Self:
        """Continue running tasks even after one fails (`--continue`)."""
        return self._record("continue")

    def dry_run(self) -> Self:
        """List what would run without executing (`--dry-run`)."""
        return self._record("dryRun")

    def output_logs(self, mode: str) -> Self:
        """Output-log mode, e.g. `full`, `hash-only`, `errors-only` (`--output-logs`)."""
        return self._record("outputLogs", mode)


class TurboTasks:
    """Typed task functions for the `turbo` CLI."""

    @staticmethod
    async def run(
        ctx: ServiceContext,
        configure: Callable[[TurboRunSettings], TurboRunSettings] | None = None,
    ) -> ExecResult:
        """Run workspace tasks: `turbo run`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "TurboTasks",
            "run",
            [configured(TurboRunSettings(), configure)],
        )
        return exec_result(answer)

