from __future__ import annotations

from collections.abc import Callable
from typing import Literal, Self

from zuke import ExecResult, ServiceContext
from zuke._facade import call, configured, exec_result
from zuke.tools._tooling import SubcommandSettings, ToolSettings

PACKAGE = "gemini"
VERSION = "1.1.2"


class GeminiRunSettings(ToolSettings):
    """Settings for a non-interactive `gemini --prompt` run — the build-friendly
    way to send a single prompt and capture the response.
    """

    def prompt(self, text: str) -> Self:
        """The prompt to run non-interactively (`--prompt`). Required."""
        return self._record("prompt", text)

    def model(self, id: str) -> Self:
        """Pin the model, e.g. `model("gemini-2.5-pro")` (`--model`)."""
        return self._record("model", id)

    def sandbox(self) -> Self:
        """Run tools inside a sandbox (`--sandbox`)."""
        return self._record("sandbox")

    def sandbox_image(self, image: str) -> Self:
        """Container image to use for the sandbox (`--sandbox-image`)."""
        return self._record("sandboxImage", image)

    def all_files(self) -> Self:
        """Include all files in the context (`--all-files`)."""
        return self._record("allFiles")

    def yolo(self) -> Self:
        """Automatically approve all tool calls (`--yolo`)."""
        return self._record("yolo")

    def approval_mode(
        self, mode: Literal["default", "auto_edit", "yolo", "plan"]
    ) -> Self:
        """How tool calls are approved (`--approval-mode`)."""
        return self._record("approvalMode", mode)

    def include_directories(self, *dirs: str) -> Self:
        """Add directories to the workspace context (`--include-directories`). Repeatable."""
        return self._record("includeDirectories", *dirs)

    def extensions(self, *names: str) -> Self:
        """Restrict to these extensions (`--extensions`). Repeatable."""
        return self._record("extensions", *names)

    def allowed_tools(self, *names: str) -> Self:
        """Allow only these tools (`--allowed-tools`). Repeatable."""
        return self._record("allowedTools", *names)

    def allowed_mcp_server_names(self, *names: str) -> Self:
        """Allow only these MCP servers (`--allowed-mcp-server-names`). Repeatable."""
        return self._record("allowedMcpServerNames", *names)

    def output_format(self, format: Literal["text", "json", "stream-json"]) -> Self:
        """Shape of the printed response (`--output-format`)."""
        return self._record("outputFormat", format)

    def debug(self) -> Self:
        """Emit debug output (`--debug`)."""
        return self._record("debug")

    def checkpointing(self) -> Self:
        """Enable checkpointing of file edits (`--checkpointing`)."""
        return self._record("checkpointing")

    def show_memory_usage(self) -> Self:
        """Report memory usage in the status bar (`--show-memory-usage`)."""
        return self._record("showMemoryUsage")


class GeminiCommandSettings(SubcommandSettings):
    """Shared builder for `gemini <group> …` subcommand groups (`mcp`,
    `extensions`): name the verb and operands with `.command(...)` and pass
    anything else with `.flag(...)`.
    """


class GeminiMcpSettings(GeminiCommandSettings):
    """Settings for a `gemini mcp …` invocation (manage MCP servers)."""


class GeminiExtensionsSettings(GeminiCommandSettings):
    """Settings for a `gemini extensions …` invocation (manage extensions)."""


class GeminiTasks:
    """Typed task functions for the Gemini CLI."""

    @staticmethod
    async def run(
        ctx: ServiceContext,
        configure: Callable[[GeminiRunSettings], GeminiRunSettings] | None = None,
    ) -> ExecResult:
        """Run a prompt non-interactively (`gemini --prompt`)."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "GeminiTasks",
            "run",
            [configured(GeminiRunSettings(), configure)],
        )
        return exec_result(answer)

    @staticmethod
    async def mcp(
        ctx: ServiceContext,
        configure: Callable[[GeminiMcpSettings], GeminiMcpSettings] | None = None,
    ) -> ExecResult:
        """Manage MCP servers (`gemini mcp …`)."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "GeminiTasks",
            "mcp",
            [configured(GeminiMcpSettings(), configure)],
        )
        return exec_result(answer)

    @staticmethod
    async def extensions(
        ctx: ServiceContext,
        configure: Callable[[GeminiExtensionsSettings], GeminiExtensionsSettings]
        | None = None,
    ) -> ExecResult:
        """Manage extensions (`gemini extensions …`)."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "GeminiTasks",
            "extensions",
            [configured(GeminiExtensionsSettings(), configure)],
        )
        return exec_result(answer)
