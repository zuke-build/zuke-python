from __future__ import annotations

from collections.abc import Callable
from typing import Self

from zuke import ExecResult, ServiceContext
from zuke._facade import call, configured, exec_result
from zuke.tools._tooling import ToolSettings

PACKAGE = "npx"
VERSION = "1.1.0"


class NpxSettings(ToolSettings):
    """Settings for the `npx` package runner."""

    def command(self, name: str) -> Self:
        """The package binary to execute (required unless call is set)."""
        return self._record("command", name)

    def package(self, *specs: str) -> Self:
        """Packages to load before running (`--package=`); repeatable."""
        return self._record("package", *specs)

    def call(self, script: str) -> Self:
        """Execute a string as if inside `npm run-script` (`--call`)."""
        return self._record("call", script)

    def yes(self) -> Self:
        """Auto-install a missing package without prompting (`--yes`)."""
        return self._record("yes")

    def no(self) -> Self:
        """Never auto-install; fail if the package is missing (`--no`)."""
        return self._record("no")

    def ignore_existing(self) -> Self:
        """Ignore binaries already present in `$PATH` (`--ignore-existing`)."""
        return self._record("ignoreExisting")

    def exec_args(self, *args: str | float) -> Self:
        """Arguments forwarded to the command."""
        return self._record("execArgs", *args)


class NpxTasks:
    """Typed task functions for the `npx` package runner."""

    @staticmethod
    async def npx(
        ctx: ServiceContext,
        configure: Callable[[NpxSettings], NpxSettings] | None = None,
    ) -> ExecResult:
        """Download and execute a package binary: `npx <command>`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "NpxTasks",
            "npx",
            [configured(NpxSettings(), configure)],
        )
        return exec_result(answer)
