"""The settings every wrapper's settings extend: `@zuke/core`'s tooling base.

Generated by ``zuke facades`` from the engine's tool spec; edit the wrapper in
zuke-build/zuke, not this file.
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import Self

from zuke._facade import Settings


class ToolSettings(Settings):
    """Abstract fluent base for tool settings. Subclasses provide the binary
    (defaultTool) and the pure subcommand argv (buildArgs);
    the base provides the shared chainers and run.
    """

    def env(self, record: Mapping[str, str]) -> Self:
        """Merge additional environment variables for the process."""
        return self._record("env", record)

    def cwd(self, path: str) -> Self:
        """Set the working directory for the process."""
        return self._record("cwd", path)

    def no_throw(self) -> Self:
        """Do not throw on a non-zero exit; inspect `code` on the output instead."""
        return self._record("noThrow")

    def quiet(self) -> Self:
        """Suppress live stdout/stderr streaming to the terminal."""
        return self._record("quiet")

    def kill_after(self, ms: float) -> Self:
        """Kill the tool if it runs longer than `ms` milliseconds, raising a
        `CommandTimeoutError`. Fires even under noThrow.
        """
        return self._record("killAfter", ms)

    def max_captured_bytes(self, bytes: float) -> Self:
        """Cap how much of **each** captured stream the run keeps in memory, in bytes
        (default 8 MiB). Once the cap is reached the oldest bytes are dropped,
        `CommandOutput.truncated` is set, and `CommandOutput.text` prefixes a
        notice. Raise it for a tool whose whole output must be parsed — a coverage
        report, a `--json` dump — and lower it to bound a chatty one. Live
        streaming to the terminal is never capped.
        """
        return self._record("maxCapturedBytes", bytes)

    def tool_path(self, path: str) -> Self:
        """Override the binary to run (e.g. an absolute path to the tool)."""
        return self._record("toolPath", path)

    def from_node_modules(self) -> Self:
        """Resolve the binary npx-style: walk up from the working directory looking
        for `node_modules/.bin/<tool>`, falling back to `PATH` on a miss. Overrides
        both the wrapper default and the ambient `ZUKE_TOOL_RESOLUTION`. Has no
        effect once toolPath is set (an explicit path always wins).
        """
        return self._record("fromNodeModules")

    def from_path(self) -> Self:
        """Resolve the binary from `PATH` only, ignoring any `node_modules/.bin`."""
        return self._record("fromPath")

    def args(self, *extra: object) -> Self:
        """Escape hatch: append raw arguments after all typed options."""
        return self._record("args", *extra)


class DynamicToolSettings(ToolSettings):
    """Fluent settings for a defineTool tool: build the argv with
    DynamicToolSettings.arg/DynamicToolSettings.flag/DynamicToolSettings.option (in call order), plus all the shared chainers
    (`cwd`, `env`, `noThrow`, `quiet`, `toolPath`, `args`).
    """

    def arg(self, *values: object) -> Self:
        """Append raw positional/argument tokens."""
        return self._record("arg", *values)

    def flag(self, name: str) -> Self:
        """Append a boolean flag, e.g. `flag("verbose")` → `--verbose` (or `-v`)."""
        return self._record("flag", name)

    def option(self, name: str, value: str | float) -> Self:
        """Append a flag and its value as two tokens, e.g. `--output dist`."""
        return self._record("option", name, value)


class SubcommandSettings(ToolSettings):
    """Base for a wrapper over a CLI organised into **subcommand groups** — a command
    path built with command plus repeatable `--flag [value]` options built
    with flag. The agent and cloud wrappers (`gh`, `gcloud`, `claude`,
    `gemini`, `codex`) share this shape; each sets its binary via
    ToolSettings.defaultTool and, when needed, a fixed prefix via
    leadingTokens or between-command global flags via middleTokens.

    The argv is assembled as
    `[...leadingTokens(), ...command, ...middleTokens(), ...flags]`, keeping every
    token a discrete argv entry so command construction stays injection-free.
    """

    def command(self, *parts: object) -> Self:
        """Append command-path tokens — the group, verb, and operands — in order."""
        return self._record("command", *parts)

    def flag(self, name: str, value: str | float | None = None) -> Self:
        """Add an arbitrary flag. With a value it renders `--name value`; without one
        the bare `--name`. Repeatable.
        """
        return self._record("flag", name, value)
