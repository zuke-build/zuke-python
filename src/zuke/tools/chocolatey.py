class ChocoTasks:
    """Typed task functions for the Chocolatey `choco` CLI."""

    @staticmethod
    async def run(
        ctx: ServiceContext,
        configure: Callable[[ChocoSettings], ChocoSettings] | None = None,
    ) -> ExecResult:
        """Run any `choco` command, built with `.command(...)`/`.flag(...)`."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "ChocoTasks",
            "run",
            [configured(ChocoSettings(), configure)],
        )
        return exec_result(answer)

    @staticmethod
    async def pack(
        ctx: ServiceContext,
        configure: Callable[[ChocoPackSettings], ChocoPackSettings] | None = None,
    ) -> ExecResult:
        """Build a `.nupkg` from a `.nuspec` (`choco pack`)."""
