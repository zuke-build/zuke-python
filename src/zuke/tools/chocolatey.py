class ChocolateyTasks:
    """Tasks for shipping a prebuilt Windows binary through Chocolatey."""

    @staticmethod
    async def package(
        ctx: ServiceContext,
        configure: Callable[[ChocolateyPackageSettings], ChocolateyPackageSettings],
    ) -> object:
        """The files of a package that installs a prebuilt binary from a zip on a
        release: `<id>.nuspec` and `tools/chocolateyinstall.ps1`. Pure: nothing
        is read or written.
        """
        return await call(
            ctx,
            PACKAGE,
            VERSION,
            "ChocolateyTasks",
            "package",
            [configured(ChocolateyPackageSettings(), configure)],
        )

    @staticmethod
    async def verify(
        ctx: ServiceContext,
        configure: Callable[[ChocolateyVerifySettings], ChocolateyVerifySettings],
    ) -> None:
        """Pack a rendered package in a temporary directory, install it from there,
        run the binary it puts on `PATH`, then uninstall it and remove the
        directory — the cleanup runs whether or not the install and check
        succeeded.
        """
        await call(
            ctx,
            PACKAGE,
            VERSION,
            "ChocolateyTasks",
            "verify",
            [configured(ChocolateyVerifySettings(), configure)],
        )

    @staticmethod
    async def publish(
        ctx: ServiceContext,
        configure: Callable[[ChocolateyPublishSettings], ChocolateyPublishSettings],
    ) -> object:
        """Push a package — rendered, or a `.nupkg` already built — to the community
        repository or another source, with its API key masked.
        """
        return await call(
            ctx,
            PACKAGE,
            VERSION,
            "ChocolateyTasks",
            "publish",
            [configured(ChocolateyPublishSettings(), configure)],
        )

    @staticmethod
    async def verify_job(
        ctx: ServiceContext,
        configure: Callable[[ChocolateyVerifyJobSettings], ChocolateyVerifyJobSettings],
    ) -> object:
        """The CI job that runs a verifying target on Windows runners, ready to
        list in `cicd({ invokes: [...] })`.
        """
        return await call(
            ctx,
            PACKAGE,
            VERSION,
            "ChocolateyTasks",
            "verifyJob",
            [configured(ChocolateyVerifyJobSettings(), configure)],
        )
