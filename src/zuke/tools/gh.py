PACKAGE = "gh"
VERSION = "1.15.0"


class GhApiSettings(ToolSettings):
    """Settings for GhTasks.api, mirroring the
    real `gh api` flags: `--method`, `--field`, `--raw-field`, `--header`,
    `--jq`, and `--silent`.
    """

    def method(self, verb: str) -> Self:
        """The HTTP method (`--method`, e.g. `"PUT"`; `gh` defaults to GET)."""
        return self._record("method", verb)

    def field(self, key: str, value: str | float | bool) -> Self:
        """Add a typed body parameter (`--field key=value`). Repeatable."""
        return self._record("field", key, value)

    def raw_field(self, key: str, value: str) -> Self:
        """Add a string body parameter (`--raw-field key=value`). Repeatable."""
        return self._record("rawField", key, value)

    def header(self, name: str, value: str) -> Self:
        """Add a request header (`--header key:value`). Repeatable."""
        return self._record("header", name, value)

    def jq(self, expression: str) -> Self:
        """Filter the response through a jq expression (`--jq`)."""
        return self._record("jq", expression)

    def silent(self) -> Self:
        """Do not print the response body (`--silent`)."""
        return self._record("silent")


class GhSettings(SubcommandSettings):
    """Settings for a `gh` invocation."""

    def repo(self, slug: str) -> Self:
        """Target repository as `OWNER/REPO` (`-R`/`--repo`)."""
        return self._record("repo", slug)


class GhTasks:
    """Typed task functions for GitHub: the `gh` CLI and the REST-only operations."""

    @staticmethod
    async def run(
        ctx: ServiceContext, configure: Callable[[GhSettings], GhSettings] | None = None
    ) -> ExecResult:
        """Run a `gh` command."""
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "GhTasks",
            "run",
            [configured(GhSettings(), configure)],
        )
        return exec_result(answer)

    @staticmethod
    async def api(
        ctx: ServiceContext,
        endpoint: str,
        configure: Callable[[GhApiSettings], GhApiSettings] | None = None,
    ) -> ExecResult:
        """Call a REST endpoint through `gh api`, with the user's `gh` credentials —
        for operations that have no CLI verb, e.g. starring a repository:
        `GhTasks.api("user/starred/zuke-build/zuke", (s) => s.method("PUT"))`.
        """
        answer = await call(
            ctx,
            PACKAGE,
            VERSION,
            "GhTasks",
            "api",
            [endpoint, configured(GhApiSettings(), configure)],
        )
        return exec_result(answer)
