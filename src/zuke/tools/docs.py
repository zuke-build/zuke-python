"""`@zuke/docs` 1.0.1: `@zuke/docs` — typed tasks that turn already-generated API documentation into agent-friendly artifacts, so neither humans nor agents have to guess an API.

Generated by ``zuke facades`` from the engine's tool spec; edit the wrapper in
zuke-build/zuke, not this file.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence

from zuke import ServiceContext
from zuke._facade import call

PACKAGE = "docs"
VERSION = "1.0.1"


class DocsTasks:
    """Typed tasks for generating and verifying API documentation."""

    @staticmethod
    async def api_docs(
        ctx: ServiceContext,
        docs: Sequence[Mapping[str, object]],
        options: Mapping[str, object] | None = None,
    ) -> object:
        """From the supplied per-package docs, generate the index, the full reference,
        and (unless disabled) each package README's API block, writing only the
        files whose content changed. Returns the paths written.
        """
        return await call(
            ctx, PACKAGE, VERSION, "DocsTasks", "apiDocs", [docs, options]
        )

    @staticmethod
    async def check_api_docs(
        ctx: ServiceContext,
        docs: Sequence[Mapping[str, object]],
        options: Mapping[str, object] | None = None,
    ) -> object:
        """Recompute every artifact and return the paths that are out of date on disk
        (empty when everything is current). Writes nothing.
        """
        return await call(
            ctx, PACKAGE, VERSION, "DocsTasks", "checkApiDocs", [docs, options]
        )

    @staticmethod
    async def check_doc_lint(
        ctx: ServiceContext, reports: Sequence[Mapping[str, object]]
    ) -> object:
        """Classify `deno doc --lint` output across packages into real defects: every
        `missing-jsdoc`, plus every `private-type-ref` whose referenced type is not
        an accepted cross-package import (in the report's `crossPackageTypes`).
        Fails safe — any other referenced type is treated as a first-party leak.
        Pure: the caller runs the linter; this classifies. Empty when clean.
        """
        return await call(ctx, PACKAGE, VERSION, "DocsTasks", "checkDocLint", [reports])
