class AzMonitorMetricsListSettings(AzSettings):
    """Settings for `az monitor metrics list`: a resource's metrics over a time
    range, one datapoint per interval.

    The CLI returns at most top time series per metric — ten unless
    told otherwise — so a query that splits by a dimension can silently lose
    series; raise `top` to cover them.
    """

    def resource(self, id: str) -> Self:
        """The resource, by full resource id (`--resource`)."""
        return self._record("resource", id)

    def metrics(self, *names: str) -> Self:
        """The metrics to read, by name (`--metrics`); repeatable."""
        return self._record("metrics", *names)

    def aggregation(
        self, *types: Literal["Average", "Count", "Maximum", "Minimum", "Total"]
    ) -> Self:
        """The aggregations to compute per interval (`--aggregation`); repeatable."""
        return self._record("aggregation", *types)

    def interval(
        self,
        interval: Literal[
            "PT1M", "PT5M", "PT15M", "PT30M", "PT1H", "PT6H", "PT12H", "PT24H"
        ],
    ) -> Self:
        """The time grain of each datapoint (`--interval`); one minute by default.
        The range set by window is not aligned to it, so the newest
        datapoint may cover an interval that is still being written.
        """
        return self._record("interval", interval)

    def start_time(self, time: str) -> Self:
        """The start of the range (`--start-time`)."""
        return self._record("startTime", time)

    def end_time(self, time: str) -> Self:
        """The end of the range (`--end-time`); now by default."""
        return self._record("endTime", time)

    def window(self, duration: str | float, end: str | None = None) -> Self:
        """The `duration` (`"15m"`, or milliseconds) up to `end` — now, unless
        given — as `--start-time` and `--end-time`.
        """
        return self._record("window", duration, end)

    def offset(self, duration: str | float) -> Self:
        """The length of the range when only one end is given (`--offset`, as
        `"30m"` or milliseconds); an hour by default.
        """
        return self._record("offset", duration)

    def filter(self, expression: str) -> Self:
        """An OData filter on the dimensions (`--filter`), e.g.
        `"ApiName eq 'GetBlob' and GeoType eq '*'"`. For plain equality, prefer
        dimension, which quotes the value.
        """
        return self._record("filter", expression)

    def dimension(self, name: str, value: str) -> Self:
        """Only the series where the dimension `name` is `value` — rendered into
        `--filter` as `name eq 'value'`, joined with `and`; repeatable.
        """
        return self._record("dimension", name, value)

    def split_by(self, *dimensions: str) -> Self:
        """Split the series by these dimensions (`--dimension`); repeatable."""
        return self._record("splitBy", *dimensions)

    def namespace(self, namespace: str) -> Self:
        """The metric namespace (`--namespace`)."""
        return self._record("namespace", namespace)

    def top(self, count: float) -> Self:
        """The most time series to return per metric (`--top`); 10 by default."""
        return self._record("top", count)

    def orderby(self, order: str) -> Self:
        """The aggregation and direction to sort series by (`--orderby`), e.g. `"sum desc"`."""
        return self._record("orderby", order)


